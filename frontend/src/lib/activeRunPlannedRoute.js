import { METERS_PER_MILE, validRouteId, validateSavedRoute } from './manualRouteBuilder.js'

// Private planned data only. Never accepts or returns recorded samples/metrics.
export function normalizePrivatePlan(value, ownerUserId) {
  if (!ownerUserId || value?.ownerUserId !== ownerUserId) return null
  try { return { ownerUserId, route: validateSavedRoute(value.route) } }
  catch { return null } // Invalid optional overlay must not destroy a recoverable recording.
}
export function privatePlanOverlay(selection) {
  if (!selection) return null
  const route = selection.route
  return { name: route.name, private: true,
    coordinates: route.geometry.coordinates.map(([lon, lat, altitude]) => [lat, lon, altitude ?? null]),
    distanceMiles: route.distanceMeters / METERS_PER_MILE,
    elevationGainFeet: route.elevation.gainMeters === null ? null : route.elevation.gainMeters / 0.3048,
    elevationPreference: route.display.elevationPreference, surface: route.display.surface }
}
// Presentation only: evenly spaced source indices, deterministic endpoints/order.
// Copies ensure Leaflet cannot mutate either the saved geometry or session snapshot.
export function plannedPresentation(points, limit = 800) {
  if (!Number.isInteger(limit) || limit < 2) throw new Error('Invalid display point limit')
  const valid = Array.isArray(points) ? points.filter(point => Array.isArray(point)
    && typeof point[0] === 'number' && Number.isFinite(point[0]) && Math.abs(point[0]) <= 90
    && typeof point[1] === 'number' && Number.isFinite(point[1]) && Math.abs(point[1]) <= 180) : []
  if (valid.length < 2) return { positions: [], sampled: false }
  const count = Math.min(limit, valid.length)
  return { positions: Array.from({ length: count }, (_, i) => valid[Math.round(i * (valid.length - 1) / (count - 1))].slice(0, 2)), sampled: count < valid.length }
}
function summaries(data, offset) {
  if (!data || data.limit !== 20 || data.offset !== offset || !Array.isArray(data.routes) || data.routes.length > 20) throw new Error('Invalid library')
  const ids = new Set()
  return data.routes.map(route => {
    // Summary fields are generated by the private endpoint; never accept owner overrides.
    if (!route || Object.keys(route).some(key => !['id', 'kind', 'schemaVersion', 'provenanceTrust', 'name', 'distanceMeters', 'targetDistanceMeters', 'elevation', 'display', 'createdAt', 'updatedAt'].includes(key))
      || !validRouteId(route.id) || ids.has(route.id) || route.kind !== 'planned' || route.schemaVersion !== 1
      || route.provenanceTrust !== 'client_declared' || typeof route.name !== 'string' || !route.name.trim() || route.name.length > 120
      || /[\u0000-\u001f]/.test(route.name) || typeof route.distanceMeters !== 'number'
      || !Number.isFinite(route.distanceMeters) || route.distanceMeters < 0 || route.distanceMeters > 1000000) throw new Error('Invalid library')
    ids.add(route.id)
    return { id: route.id, name: route.name }
  })
}
// Uses the existing API auth-session fence via injected get/current. Each result
// is gated again after await; choosing none, auth changes and disposal invalidate it.
export function createPrivatePlanPicker({ ownerUserId, current, get, onChange }) {
  let state = { routes: [], offset: 0, selection: null, loading: false, error: '' }
  let generation = 0, disposed = false, controller
  const valid = () => !disposed && Boolean(ownerUserId) && current()
  const emit = () => { if (!disposed) onChange({ ...state }) }
  const cancel = () => { generation++; controller?.abort(); controller = new AbortController() }
  const update = async (work, message) => {
    if (!valid()) return
    cancel(); const token = generation
    state = { ...state, loading: true, error: '' }; emit()
    try {
      const patch = await work(controller.signal)
      if (valid() && token === generation) state = { ...state, ...patch, loading: false }
    } catch {
      // Never log request errors/coordinates. Fail closed; no silent fallback.
      if (valid() && token === generation) state = { ...state, selection: null, loading: false, error: message }
    }
    if (valid() && token === generation) emit()
  }
  return {
    list(offset = 0) {
      if (!Number.isInteger(offset) || offset < 0 || offset > 1000000) return Promise.resolve()
      return update(async signal => {
        const { data } = await get('/user-routes', { signal, params: { limit: 20, offset } })
        return { routes: summaries(data, offset), offset }
      }, 'Private routes unavailable. You can start with no planned route.')
    },
    select(id, { restore = false } = {}) {
      cancel(); state = { ...state, selection: null, loading: false, error: '' }; emit()
      if (id === '') return Promise.resolve()
      if (!validRouteId(id) || (!restore && !state.routes.some(route => route.id === id))) {
        state = { ...state, error: 'Private route unavailable. Choose another route or no route.' }; emit(); return Promise.resolve()
      }
      return update(async signal => {
        const { data } = await get(`/user-routes/${id}`, { signal })
        const selection = normalizePrivatePlan({ ownerUserId, route: data?.route }, ownerUserId)
        if (!selection || selection.route.id !== id) throw new Error('Invalid private route')
        return { selection }
      }, 'Private route unavailable. Choose another route or no route.')
    },
    revoke() { cancel(); state = { routes: [], offset: 0, selection: null, loading: false, error: 'Account changed. Private planned route cleared.' }; emit() },
    dispose() { cancel(); disposed = true },
  }
}
